//! savestate: QEMU/KVM sandboxes on Kubernetes that save their complete state as
//! checkpoints and start any number of new sandboxes from one.
//!
//! One static binary provides every role; each role is a module here (see
//! "Architecture" in `docs/design.md`):
//!
//! - [`controller`]: the cluster-wide operator (Deployment, one replica).
//! - [`node`]: the per-node agent (`DaemonSet`) that owns `/var/lib/savestate`.
//! - [`launcher`]: one per VM pod; starts and supervises QEMU over QMP.
//! - [`cli`]: the user-facing verbs, shorthand over the `Sandbox` and `Checkpoint`
//!   objects.
//!
//! The CRD types and the installation config live in the `savestate-api` crate.
//! QEMU, QMP and guest-agent code comes from orbd's shared crates.

pub mod cli;
pub mod controller;
pub mod launcher;
pub mod node;
pub mod telemetry;

use std::path::Path;

use anyhow::Context;
use savestate_api::Config;

/// Read and check the installation config at `path`.
pub fn load_config(path: &Path) -> anyhow::Result<Config> {
    let yaml =
        std::fs::read_to_string(path).with_context(|| format!("reading {}", path.display()))?;
    Config::from_yaml(&yaml).with_context(|| format!("in {}", path.display()))
}

/// Every `CustomResourceDefinition` as one multi-document YAML stream; this is
/// `deploy/crds/savestate.dev.yaml`.
pub fn crds_yaml() -> anyhow::Result<String> {
    let mut out =
        String::from("# Generated by `savestate crds` from crates/savestate-api. Do not edit.\n");
    for crd in savestate_api::crds() {
        out.push_str("---\n");
        out.push_str(&serde_saphyr::to_string(&crd)?);
    }
    Ok(out)
}

/// The error every role and verb returns until it is built.
fn not_implemented(what: &str) -> anyhow::Error {
    anyhow::anyhow!("`savestate {what}` is not implemented yet")
}
